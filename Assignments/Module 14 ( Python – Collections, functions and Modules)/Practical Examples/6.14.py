# 14 Write a Python program to access values using keys from a dictionary.

data = {
    'id' : 18,
    'name' : 'virat',
    'city' : 'Rajkot',
    'sub' : 'python',
    'field' : 'IT'
}
print('Id:',data['id'])
print('NAME:',data['name'])
print('CITY:',data['city'])
print('SUBJECT:',data['sub'])
print('FIELD:',data['field'])