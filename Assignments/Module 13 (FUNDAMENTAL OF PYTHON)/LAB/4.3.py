#Practical Example 7: Write a Python program to calculate grades based on percentage using
#if-else ladder.

marks = float(input("Enter your marks"))

if marks >= 90:
    print("Gread A")

elif marks >= 70:
    print("Gread B")

elif marks >= 55:
    print("Grade C ")

elif marks >= 40:
    print("Grade D")

else :
    print("Fail")
